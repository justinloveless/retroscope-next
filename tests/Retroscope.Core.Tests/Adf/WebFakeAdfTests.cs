using System.Text.Json;
using System.Text.Json.Nodes;
using Retroscope.Core.Adf;
using Retroscope.Core.Markup;
using Retroscope.Core.Tests.Scaffold;

namespace Retroscope.Core.Tests.Adf;

/// <summary>
/// The web fake's Jira serves the read view from markup and islands, and the rich editor's edit view from a golden
/// of the real projection of the issue's <c>adf</c>. These checks keep the three in step: the ADF renders, through
/// the real pipeline, to exactly the Doc the fake serves, and the golden is regenerated from the projection.
/// </summary>
[Trait("Category", "Adf")]
public sealed class WebFakeAdfTests {
    private static readonly (string File, string Key)[] FixtureIssues = [
        ("tests/web-fake-server/fixtures/jira.json", "RS-12"),
        ("tests/web-fake-server/demo/jira.json", "DEMO-123"),
    ];

    public static TheoryData<string, string> Issues() => new(FixtureIssues);

    [Theory]
    [MemberData(nameof(Issues))]
    public void The_fixture_ADF_renders_to_the_Doc_the_fake_serves(string file, string key) {
        var issue = Issue(file, key);
        var description = AdfToDoc.Description(issue.GetProperty("adf"), Attachments(issue));

        var expected = FakeDoc(issue);
        var actual = Normalize(JsonNode.Parse(DocJson.Serialize(description.Doc))!);
        Assert.True(JsonNode.DeepEquals(expected, actual), $"fake   {expected.ToJsonString()}\nserver {actual.ToJsonString()}");
        Assert.True(description.Editable);
    }

    /// <summary>
    /// The edit views the fake serves, generated from the real projection (the protocol.gen.js pattern): the projected
    /// ADF with its tokens, the opaque parts with the server's labels and previews, the mark tokens, the media table,
    /// and the originals a save restores. A projection change regenerates the file, and CI's clean-tree step fails until
    /// it is committed.
    /// </summary>
    [Fact]
    public void The_fake_serves_the_projected_edit_views() {
        var issues = new JsonObject();
        foreach (var (file, key) in FixtureIssues) {
            var issue = Issue(file, key);
            var attachments = Attachments(issue);
            var view = AdfEditProjection.Project(issue.GetProperty("adf"), attachments);

            Assert.True(view.Editable);
            Assert.Equal(["extension", "inlineExtension"], view.Opaque.Select(part => part.Kind).Order(StringComparer.Ordinal));
            Assert.Equal(["annotation"], view.Marks.Select(mark => mark.Kind));
            Assert.Single(view.Base.Keeps);
            Assert.All(view.Media, media => Assert.NotNull(media.AttachmentId));
            issues[key] = EditView(view, attachments);
        }
        var golden = new JsonObject {
            ["about"] = "Generated by WebFakeAdfTests from Core/Adf/AdfEditProjection; do not edit. The web fake's Jira serves these edit views and restores their tokens on save.",
            ["issues"] = issues,
        };

        AssertCurrent(EditViewsPath, golden.ToJsonString(GoldenJson) + "\n");
    }

    private const string EditViewsPath = "tests/web-fake-server/edit-views.gen.json";

    private static readonly JsonSerializerOptions GoldenJson = new() {
        WriteIndented = true,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    // The shape of GET issues/{key}/description (JiraDescriptionEditView), plus the originals the server keeps.
    private static JsonObject EditView(AdfEditView view, List<AdfAttachment> attachments) {
        var opaque = new JsonArray();
        foreach (var part in view.Opaque) {
            using var original = JsonDocument.Parse(part.Raw);
            opaque.Add(new JsonObject {
                ["ref"] = part.Ref,
                ["kind"] = part.Kind,
                ["inline"] = part.Inline,
                ["label"] = part.Label,
                ["preview"] = JsonNode.Parse(DocJson.Serialize(AdfToDoc.Render(original.RootElement, attachments))),
            });
        }
        return new JsonObject {
            ["adf"] = JsonNode.Parse(view.Adf),
            ["media"] = new JsonArray([.. view.Media.Select(m => (JsonNode)new JsonObject {
                ["id"] = m.Id, ["attachmentId"] = m.AttachmentId, ["name"] = m.Name, ["image"] = m.Image, ["w"] = m.Width, ["h"] = m.Height,
            })]),
            ["opaque"] = opaque,
            ["marks"] = new JsonArray([.. view.Marks.Select(m => (JsonNode)new JsonObject { ["ref"] = m.Ref, ["kind"] = m.Kind })]),
            ["limits"] = new JsonObject {
                ["nodes"] = view.Limits.Nodes, ["depth"] = view.Limits.Depth, ["text"] = view.Limits.Text, ["bytes"] = view.Limits.Bytes,
            },
            // Each original as the bytes Jira holds, so the fake can splice them back as the server does.
            ["originals"] = new JsonObject {
                ["opaque"] = Raws(view.Base.Opaque.Select(e => (e.Key, (IEnumerable<string>)e.Value.Raws))),
                ["marks"] = Raws(view.Base.Marks.Select(e => (e.Key, (IEnumerable<string>)e.Value.Raws))),
                ["keeps"] = new JsonObject([.. view.Base.Keeps.Select(e => KeyValuePair.Create(e.Key,
                    (JsonNode?)new JsonObject([.. e.Value.Members.Select(m => KeyValuePair.Create(m.Key, (JsonNode?)JsonValue.Create(m.Value)))])))]),
            },
        };
    }

    private static JsonObject Raws(IEnumerable<(string Ref, IEnumerable<string> Raws)> entries) =>
        new([.. entries.Select(e => KeyValuePair.Create(e.Ref, (JsonNode?)new JsonArray([.. e.Raws.Select(raw => (JsonNode)JsonValue.Create(raw)!)])))]);

    private static void AssertCurrent(string relativePath, string generated) {
        var path = Path.Combine(RepoRoot.Path, relativePath);
        var committed = File.Exists(path) ? File.ReadAllText(path) : null;
        if (committed == generated) {
            return;
        }
        File.WriteAllText(path, generated);
        Assert.Fail($"{relativePath} was stale and has been regenerated; review and commit it.");
    }

    // What tests/web-fake-server/jira.js descriptionDoc() serves: the markup parsed, each island's Doc spliced in.
    private static JsonNode FakeDoc(JsonElement issue) {
        var doc = JsonNode.Parse(DocJson.Serialize(MarkupParser.Parse(issue.GetProperty("description").GetString()!, MarkupDialect.JiraDescription)))!;
        foreach (var block in doc["c"]!.AsArray()) {
            if ((string?)block!["t"] == "island") {
                block["c"] = new JsonArray(JsonNode.Parse(issue.GetProperty("islands").GetProperty((string)block["id"]!).GetRawText()));
            }
        }
        return Normalize(doc);
    }

    // Island ids differ by design: the fake's are hand-written, the server's are content hashes.
    private static JsonNode Normalize(JsonNode doc) {
        foreach (var block in doc["c"]!.AsArray()) {
            if ((string?)block!["t"] == "island") {
                block["id"] = "island";
            }
        }
        return doc;
    }

    private static List<AdfAttachment> Attachments(JsonElement issue) =>
        [.. issue.GetProperty("attachments").EnumerateArray().Select(a => new AdfAttachment(
            a.GetProperty("id").GetString()!, a.GetProperty("filename").GetString()!, a.GetProperty("mimeType").GetString()!, DateTimeOffset.MinValue))];

    private static JsonElement Issue(string file, string key) {
        using var document = JsonDocument.Parse(File.ReadAllBytes(Path.Combine(RepoRoot.Path, file)));
        return document.RootElement.GetProperty("issues").EnumerateArray().Single(issue => issue.GetProperty("key").GetString() == key).Clone();
    }
}
